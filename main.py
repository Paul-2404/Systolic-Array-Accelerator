def reset_systolic_array():
    print("\nResetting accelerator...")
    mmio_wrapper.write(ADDR_CTRL, 0x02)
    time.sleep(0.001)
    mmio_wrapper.write(ADDR_CTRL, 0x00)
    time.sleep(0.001)
    print("Reset complete.")

# ============================================================
# 8. CLEAR RESULT BRAM
# ============================================================
def clear_result_bram(num_tiles):
    result_size = num_tiles * BYTES_PER_TILE

    print("\nClearing result BRAM")
    print("  Range: 0x%08X - 0x%08X" % (
        OFFSET_RESULT,
        OFFSET_RESULT + result_size - 1
    ))

    for address in range(
        OFFSET_RESULT,
        OFFSET_RESULT + result_size,
        4
    ):
        write_bram_word(address, 0)

# ============================================================
# 9. READ / RECONSTRUCT ONE 4x4 TILE
# ============================================================
def reconstruct_output(result_bytes):
    if len(result_bytes) != 16:
        raise ValueError("A 4x4 tile must contain exactly 16 result bytes")

    output = np.zeros((4, 4), dtype=np.uint8)

    # Hardware ordering from the existing tiling driver:
    # index = col * 4 + row
    for col in range(4):
        for row in range(4):
            index = col * 4 + row
            output[row, col] = result_bytes[index]

    return output


def read_result_tile(result_offset, verbose=True):
    result_bytes = []

    for word_idx in range(4):
        address = result_offset + word_idx * 4
        word = read_bram_word(address)
        bytes_ = unpack_uint8x4(word)

        if verbose:
            print(
                "  Result word[%d] @ 0x%08X : 0x%08X -> %s" %
                (word_idx, address, word, bytes_)
            )

        result_bytes.extend(bytes_)

    return reconstruct_output(result_bytes)

