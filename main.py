# 13. LOAD PACKED WEIGHTS / BIASES / M / SHIFT
# ============================================================

def load_packed_weights(filename, K, N):
    """
    Reconstruct the K x N INT8 weight matrix from the packed
    format generated by train_quantize.py.

    Packing order:

        output neurons in groups of 4
            input feature 0
            input feature 1
            ...
            input feature K-1

    Each uint32 word contains four weights:

        byte 0 -> neuron + 0
        byte 1 -> neuron + 1
        byte 2 -> neuron + 2
        byte 3 -> neuron + 3
    """

    if not os.path.exists(filename):
        raise FileNotFoundError(
            "%s not found. Copy the generated file into "
            "this directory." % filename
        )

    words = np.fromfile(filename, dtype=np.uint32)

    padded_N = ((N + ARRAY_DIM - 1) // ARRAY_DIM) * ARRAY_DIM
    expected_words = (padded_N // ARRAY_DIM) * K

    if len(words) != expected_words:
        raise ValueError(
            "%s must contain %d uint32 words, got %d"
            % (filename, expected_words, len(words))
        )

    weights = np.zeros((K, N), dtype=np.int8)

    word_index = 0

    for output_base in range(0, padded_N, ARRAY_DIM):

        for k in range(K):

            word = int(words[word_index])
            word_index += 1

            for lane in range(ARRAY_DIM):

                neuron = output_base + lane

                if neuron < N:

                    value = (word >> (8 * lane)) & 0xFF

                    if value >= 128:
                        value -= 256

                    weights[k, neuron] = value

    return weights


def load_biases(filename, N):
    """
    Bias files contain signed INT32 values, one per 32-bit word,
    padded to a multiple of four outputs.
    """

    if not os.path.exists(filename):
        raise FileNotFoundError(
            "%s not found. Copy the generated file into "
            "this directory." % filename
        )

    values = np.fromfile(filename, dtype=np.int32)

    padded_N = ((N + ARRAY_DIM - 1) // ARRAY_DIM) * ARRAY_DIM

    if len(values) != padded_N:
        raise ValueError(
            "%s must contain %d INT32 values, got %d"
            % (filename, padded_N, len(values))
        )

    return values[:N].copy()


def load_quantization_parameters():
    if not os.path.exists(M_FILE):
        raise FileNotFoundError("%s not found." % M_FILE)

    if not os.path.exists(SHIFT_FILE):
        raise FileNotFoundError("%s not found." % SHIFT_FILE)

    M = np.load(M_FILE).astype(np.int64).reshape(-1)
    SHIFT = np.load(SHIFT_FILE).astype(np.int32).reshape(-1)

    if len(M) != 3:
        raise ValueError(
            "M.npy must contain exactly 3 values, got %d" % len(M)
        )

    if len(SHIFT) != 3:
        raise ValueError(
            "SHIFT.npy must contain exactly 3 values, got %d" % len(SHIFT)
        )

    print("\nQuantization parameters:")
    for i in range(3):
        print(
            "  L%d: M=%d SHIFT=%d"
            % (i + 1, int(M[i]), int(SHIFT[i]))
        )

    return M, SHIFT


