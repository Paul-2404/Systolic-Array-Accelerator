# 12. LOAD QUANTIZED INPUT
# ============================================================
def load_input():
    if not os.path.exists(INPUT_FILE):
        raise FileNotFoundError(
            "%s not found. Copy the file generated by "
            "train_quantize.py into this directory." % INPUT_FILE
        )

    # input_4_images.bin contains 784 uint32 words.
    # Each word packs one feature from four images:
    #
    #   [7:0]   = image 0
    #   [15:8]  = image 1
    #   [23:16] = image 2
    #   [31:24] = image 3
    words = np.fromfile(INPUT_FILE, dtype=np.uint32)

    if len(words) != 784:
        raise ValueError(
            "%s must contain exactly 784 uint32 words, got %d"
            % (INPUT_FILE, len(words))
        )

    data = np.zeros((NUM_IMAGES, 784), dtype=np.int8)

    for feature in range(784):
        word = int(words[feature])

        for image in range(NUM_IMAGES):
            value = (word >> (8 * image)) & 0xFF

            # Convert two's-complement byte to signed INT8.
            if value >= 128:
                value -= 256

            data[image, feature] = value

    print("\nInput loaded from:")
    print("  File  :", INPUT_FILE)
    print("  Shape :", data.shape)
    print("  Dtype :", data.dtype)
    print("  Min   :", int(data.min()))
    print("  Max   :", int(data.max()))

    return data


