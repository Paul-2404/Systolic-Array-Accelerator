# 10. RUN ONE 4x4 TILE
# ============================================================
# This is the same tile-level driver mechanism used by
# tiled_test.py. It is NOT a separate run_layer driver.
# ============================================================
def run_accelerator_tile(
    tile_input,
    tile_weights,
    tile_bias,
    K,
    M,
    shift,
    result_offset,
    monitor=None,
    segment_name=None,
):
    tile_input = np.asarray(tile_input, dtype=np.int8)
    tile_weights = np.asarray(tile_weights, dtype=np.int8)
    tile_bias = np.asarray(tile_bias, dtype=np.int32)

    if tile_input.shape != (K, 4):
        raise ValueError(
            "tile_input must have shape (%d, 4), got %s" %
            (K, tile_input.shape)
        )

    if tile_weights.shape != (K, 4):
        raise ValueError(
            "tile_weights must have shape (%d, 4), got %s" %
            (K, tile_weights.shape)
        )

    if tile_bias.shape != (4,):
        raise ValueError("tile_bias must have shape (4,)")

    # ---------------- INPUT BRAM ----------------
    for k in range(K):
        write_bram_word(
            OFFSET_INPUT + k * 4,
            pack_int8x4(tile_input[k])
        )

    # ---------------- WEIGHT BRAM ----------------
    for k in range(K):
        write_bram_word(
            OFFSET_WEIGHT + k * 4,
            pack_int8x4(tile_weights[k])
        )

    #print("\n--- EXPECTED INPUT ---")
    #for k in range(min(K, 10)):
    #    print(
    #        f"word[{k:2d}] expected -> "
    #        f"{tile_input[k].tolist()}"
    #    )

    #print("\n--- EXPECTED WEIGHT ---")
    #for k in range(min(K, 10)):
    #    print(
    #       f"word[{k:2d}] expected -> "
    #        f"{tile_weights[k].tolist()}"
    #    )

    # ---------------------------------------------------------
    # DEBUG: Read back input and weight BRAM
    # ---------------------------------------------------------

    #debug_read_bram_words(
    #	mmio_bram,
    #	OFFSET_INPUT,
    #	min(K, 10),
    #	"INPUT"
    #)

    #debug_read_bram_words(
    #	mmio_bram,
    #	OFFSET_WEIGHT,
    #	min(K, 10),
    #	"WEIGHT"
    #	)
    # ---------------- BIAS BRAM ----------------
    for i in range(4):
        write_bram_word(
            OFFSET_BIAS + i * 4,
            int(tile_bias[i])
        )

    # ---------------- WRAPPER CONFIG ----------------
    mmio_wrapper.write(ADDR_INPUT_PTR, OFFSET_INPUT)
    mmio_wrapper.write(ADDR_BIAS_PTR, OFFSET_BIAS)
    mmio_wrapper.write(ADDR_WEIGHT_PTR, OFFSET_WEIGHT)
    mmio_wrapper.write(ADDR_RESULT_PTR, result_offset)

    # NO_ADD is K = number of MAC operations.
    mmio_wrapper.write(ADDR_NO_ADD, K)
    mmio_wrapper.write(ADDR_M_VAL, int(M))
    mmio_wrapper.write(ADDR_SHIFT_VAL, int(shift))

    # ---------------- START ----------------
    # Measure only the accelerator compute window: after the software has
    # finished writing the input, weights, bias, and control registers, and
    # immediately before the start pulse is asserted.
    if monitor and segment_name:
        start_time = monitor.mark_segment_start(segment_name)

    mmio_wrapper.write(ADDR_CTRL, 0x01)

    # ---------------- WAIT FOR DONE ----------------
    timeout_sec = 5.0
    start_wait = time.time()

    while True:
        status = mmio_wrapper.read(ADDR_STATUS)
        busy = status & 0x01
        done = (status >> 1) & 0x01

        if done:
            break

        if time.time() - start_wait > timeout_sec:
            raise RuntimeError(
                "Tile accelerator timeout. STATUS=0x%08X RESULT_CNT=%d" %
                (status, mmio_wrapper.read(ADDR_RESULT_CNT))
            )

    if monitor and segment_name:
        monitor.mark_segment_end(segment_name, start_time)

    # ---------------- READ RESULT ----------------
    tile_output = read_result_tile(result_offset, verbose=False)

    return tile_output

