    # --------------------------------------------------------
    weights_l3_padded = np.zeros((64, 12), dtype=np.int8)
    weights_l3_padded[:, :10] = weights_l3

    bias_l3_padded = np.zeros(12, dtype=np.int32)
    bias_l3_padded[:10] = bias_l3

    l3_output_padded = run_tiled_layer(
        l2_output,
        weights_l3_padded,
        bias_l3_padded,
        L3_M,
        L3_SHIFT,
        "LAYER 3 (64 -> 12 hardware / 10 real)",
        monitor=monitor,
    )

    # Discard hardware outputs 10 and 11.
    final_output = l3_output_padded[:, :10]

    # --------------------------------------------------------
    # FINAL RESULTS & CLASSIFICATION VERIFICATION
    # --------------------------------------------------------
    print("\n========================================")
    print("FINAL NETWORK OUTPUT")
    print("========================================")
    print("Final output shape:", final_output.shape)
    print(final_output)

    predictions = np.argmax(final_output, axis=1)

    print("\nPredicted classes:")
    for image in range(NUM_IMAGES):
        print(
            "  Image %d -> class %d" %
            (image, int(predictions[image]))
        )

    # Save the FPGA-produced final output for later inspection.
    np.save("fpga_output.npy", final_output)
    print("\nSaved final FPGA output to fpga_output.npy")

    monitor.end_execution()

    # --------------------------------------------------------
    # COMPUTING ACTUAL & THEORETICAL THROUGHPUT METRICS
    # --------------------------------------------------------
    from fpga_metrics_calculator import calculate_layer_macs, calculate_memory_access, ARRAY_DIM, CLOCK_FREQUENCY_MHZ

    # 1. Real measured timing data (ms) from hardware execution start only.
    # This excludes the host-side BRAM write/setup time and measures the
    # accelerator compute window after the software has finished loading data.
    def layer_compute_time_ms(layer_name: str, num_tiles: int) -> float:
        return sum(
            monitor.get_statistics(f"{layer_name}_tile_{tile}").get('mean_ms', 0.0)
            for tile in range(num_tiles)
        )

    t_l1 = layer_compute_time_ms("LAYER 1 (784 -> 128)", 32)
    t_l2 = layer_compute_time_ms("LAYER 2 (128 -> 64)", 16)
    t_l3 = layer_compute_time_ms("LAYER 3 (64 -> 12 hardware / 10 real)", 3)
    total_time_ms = t_l1 + t_l2 + t_l3

    # 2. Layer MAC calculations
    macs_l1 = calculate_layer_macs('L1', NUM_IMAGES)
    macs_l2 = calculate_layer_macs('L2', NUM_IMAGES)
    macs_l3 = calculate_layer_macs('L3', NUM_IMAGES)
    total_macs = macs_l1 + macs_l2 + macs_l3

    # 3. Memory bytes transferred
    bytes_l1 = calculate_memory_access('L1', NUM_IMAGES)
    bytes_l2 = calculate_memory_access('L2', NUM_IMAGES)
    bytes_l3 = calculate_memory_access('L3', NUM_IMAGES)
    total_bytes = bytes_l1 + bytes_l2 + bytes_l3

    # 4. Throughput Calculations
    # Theoretical Peak Max Throughput (Hardware Limit @ 100MHz)
    peak_macs_per_cycle = ARRAY_DIM * ARRAY_DIM * 2  # 32 ops/cycle
    theoretical_peak_gmacs = (peak_macs_per_cycle * CLOCK_FREQUENCY_MHZ) / 1000.0  # 3.20 GMACs/s

    # Actual End-to-End System Throughputs (includes Python driver & AXI overhead)
    tp_l1_gmacs = (macs_l1 / (t_l1 / 1000.0)) / 1e9 if t_l1 > 0 else 0
    tp_l2_gmacs = (macs_l2 / (t_l2 / 1000.0)) / 1e9 if t_l2 > 0 else 0
    tp_l3_gmacs = (macs_l3 / (t_l3 / 1000.0)) / 1e9 if t_l3 > 0 else 0

    actual_max_throughput_gmacs = max(tp_l1_gmacs, tp_l2_gmacs, tp_l3_gmacs)
    best_layer = 'L1' if actual_max_throughput_gmacs == tp_l1_gmacs else ('L2' if actual_max_throughput_gmacs == tp_l2_gmacs else 'L3')

    actual_overall_throughput_gmacs = (total_macs / (total_time_ms / 1000.0)) / 1e9 if total_time_ms > 0 else 0
    actual_overall_mmacs = actual_overall_throughput_gmacs * 1000.0
    actual_max_mmacs = actual_max_throughput_gmacs * 1000.0

    actual_images_per_sec = (NUM_IMAGES / (total_time_ms / 1000.0)) if total_time_ms > 0 else 0
    actual_bandwidth_mb_s = (total_bytes / (total_time_ms / 1000.0)) / 1e6 if total_time_ms > 0 else 0
    actual_bandwidth_gb_s = actual_bandwidth_mb_s / 1000.0

    # Efficiency Ratios
    overall_efficiency = (actual_overall_throughput_gmacs / theoretical_peak_gmacs) * 100
    peak_utilization = (actual_max_throughput_gmacs / theoretical_peak_gmacs) * 100

