# 11. RUN ONE LAYER WITH TILING
# ============================================================
# Runs a single layer using 4x4 tiling.
# No golden model comparison - just executes the layer.
# ============================================================
def run_tiled_layer(
    hardware_input,
    weight_data,
    bias_data,
    M,
    shift,
    layer_name,
    monitor=None,
):
    hardware_input = np.asarray(hardware_input, dtype=np.int8)
    weight_data = np.asarray(weight_data, dtype=np.int8)
    bias_data = np.asarray(bias_data, dtype=np.int32)

    if hardware_input.ndim == 1:
        hardware_input = hardware_input[np.newaxis, :]

    num_images, K = hardware_input.shape
    num_neurons = weight_data.shape[1]

    if weight_data.shape[0] != K:
        raise ValueError(
            "weight_data has %d input features, but input has %d" %
            (weight_data.shape[0], K)
        )

    if len(bias_data) != num_neurons:
        raise ValueError(
            "bias_data has %d values, but weight_data has %d neurons" %
            (len(bias_data), num_neurons)
        )

    if num_neurons % 4 != 0:
        raise ValueError(
            "Number of neurons (%d) must be divisible by 4" %
            num_neurons
        )

    hardware_output = np.zeros((num_images, num_neurons), dtype=np.uint8)

    num_tiles = num_neurons // 4

    print("\n%s:" % layer_name)
    print("  Input shape  : (%d, %d)" % (num_images, K))
    print("  Output shape : (%d, %d)" % (num_images, num_neurons))
    print("  Tiles        : %d (4 neurons per tile)" % num_tiles)
    print("  M=%d, SHIFT=%d" % (M, shift))

    reset_systolic_array()
    clear_result_bram(num_tiles)

    for tile in range(num_tiles):
        neuron_start = tile * 4
        neuron_end = neuron_start + 4

        tile_weights = weight_data[:, neuron_start:neuron_end]
        tile_bias = bias_data[neuron_start:neuron_end]

        result_offset = OFFSET_RESULT + tile * BYTES_PER_TILE

        print(
            "\nTile %d/%d: neurons %d-%d | result BRAM 0x%08X-0x%08X" %
            (
                tile + 1,
                num_tiles,
                neuron_start,
                neuron_end - 1,
                result_offset,
                result_offset + BYTES_PER_TILE - 1,
            )
        )

        # The software keeps activations as:
        #   (num_images, K)
        # but the FPGA tile interface expects:
        #   (K, 4)
        # where the 4 columns are the four images processed in parallel.
        #
        # Example for L1:
        #   hardware_input : (4, 784)
        #   tile_input     : (784, 4)
        #
        # The weight tile remains (K, 4), where its four columns are
        # the four neurons in this output tile.
        tile_input = hardware_input.T

        #if layer_name == "LAYER 1 (784 -> 128)" and tile == 0:
        #    print("\n--- L1 TILE INPUT NONZERO CHECK ---")

        #    nz = np.argwhere(tile_input != 0)

        #    print("Number of nonzero elements:", len(nz))

        #    for i in range(min(20, len(nz))):
        #        k, image = nz[i]
        #        print(
        #            f"feature={k}, image={image}, "
        #        f"value={int(tile_input[k, image])}"
        #        )
        #if tile_input.shape != (K, NUM_IMAGES):
        #    raise ValueError(
        #        "Internal tile input orientation error: expected (%d, %d), got %s" %
        #        (K, NUM_IMAGES, tile_input.shape)
        #    )

        tile_segment_name = f"{layer_name}_tile_{tile}"
        tile_output = run_accelerator_tile(
            tile_input=tile_input,
            tile_weights=tile_weights,
            tile_bias=tile_bias,
            K=K,
            M=M,
            shift=shift,
            result_offset=result_offset,
            monitor=monitor,
            segment_name=tile_segment_name if monitor else None,
        )

        # run_accelerator_tile() reconstructs results as:
        #   (4 images, 4 neurons)
        # so no transpose is needed here.

        hardware_output[:, neuron_start:neuron_end] = tile_output

    print("\n%s output:" % layer_name)
    print(hardware_output)

    return hardware_output

