# 6. PACK / UNPACK
# ============================================================
def pack_int8x4_vectorized(matrix_kx4):
    """
    Vectorized pack of (K, 4) int8 array into (K,) uint32 array.
    Runs in compiled C (NumPy) with zero Python loop overhead.
    """
    u = np.asarray(matrix_kx4, dtype=np.uint8).view(np.uint32)
    return u.flatten()


def pack_int8x4(values):
    values = np.asarray(values, dtype=np.int8)

    if values.shape != (4,):
        raise ValueError("pack_int8x4 requires exactly 4 values")

    b0 = int(values[0]) & 0xFF
    b1 = int(values[1]) & 0xFF
    b2 = int(values[2]) & 0xFF
    b3 = int(values[3]) & 0xFF

    return b0 | (b1 << 8) | (b2 << 16) | (b3 << 24)


def unpack_uint8x4(word):
    return [
        (word >> 0) & 0xFF,
        (word >> 8) & 0xFF,
        (word >> 16) & 0xFF,
        (word >> 24) & 0xFF,
    ]

