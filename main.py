# 5. BASIC BRAM ACCESS
# ============================================================
def write_bram_word(offset, value):
    mmio_bram.write(offset, int(value) & 0xFFFFFFFF)


def write_bram_block(base_offset, uint32_array):
    """Write an entire array of uint32 values to BRAM in a fast block"""
    uint32_array = np.ascontiguousarray(uint32_array, dtype=np.uint32)
    # PYNQ MMIO supports byte buffer write or slice assignment
    try:
        mmio_bram.write(base_offset, uint32_array.tobytes())
    except (TypeError, AttributeError):
        # Fallback if direct buffer write is unsupported on specific pynq version
        for i, val in enumerate(uint32_array):
            mmio_bram.write(base_offset + i * 4, int(val))


def read_bram_word(offset):
    return mmio_bram.read(offset)

