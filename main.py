    print(f"  • Actual Max Throughput ({best_layer}):        {actual_max_throughput_gmacs:.6f} GMACs/s  ({actual_max_mmacs:.2f} MMACs/s, {peak_utilization:.4f}% peak)")
    print(f"  • Actual Overall Throughput:         {actual_overall_throughput_gmacs:.6f} GMACs/s  ({actual_overall_mmacs:.2f} MMACs/s, {overall_efficiency:.4f}% efficiency)")
    print(f"  • Actual Inference Speed:            {actual_images_per_sec:.2f} images/sec")
    print(f"  • Actual Memory Bandwidth:          {actual_bandwidth_mb_s:.2f} MB/s  ({actual_bandwidth_gb_s:.4f} GB/s)")
    print(f"  • Total Execution Latency:           {total_time_ms:.4f} ms")
